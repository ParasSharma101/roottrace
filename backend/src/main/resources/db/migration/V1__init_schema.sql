-- ====================================================================
-- RootTrace: Baseline Database Schema (V1)
-- ====================================================================

-- 1. Incidents Table (Core domain entity)
CREATE TABLE incidents (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
    severity_level VARCHAR(16) NOT NULL DEFAULT 'SEV2',
    title VARCHAR(255) NOT NULL,
    summary TEXT,
    start_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolution_time TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_incident_status CHECK (status IN ('OPEN', 'INVESTIGATING', 'RESOLVED')),
    CONSTRAINT chk_incident_severity CHECK (severity_level IN ('SEV1', 'SEV2', 'SEV3', 'SEV4'))
);

-- 2. Alerts Table (Ingested from monitoring tools like Datadog, PagerDuty)
CREATE TABLE alerts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    incident_id UUID REFERENCES incidents(id) ON DELETE SET NULL,
    source VARCHAR(64) NOT NULL,
    alert_type VARCHAR(128) NOT NULL,
    service_name VARCHAR(128) NOT NULL,
    raw_payload JSONB NOT NULL,
    triggered_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Deployments Table (Correlated release events)
CREATE TABLE deployments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    service_name VARCHAR(128) NOT NULL,
    deployment_time TIMESTAMPTZ NOT NULL,
    version_tag VARCHAR(64) NOT NULL,
    github_commit_hash VARCHAR(64) NOT NULL,
    environment VARCHAR(32) NOT NULL DEFAULT 'production',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. GitHub PRs Table (Code changes linked to deployments)
CREATE TABLE github_prs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    deployment_id UUID REFERENCES deployments(id) ON DELETE CASCADE,
    pr_number INT NOT NULL,
    title VARCHAR(255) NOT NULL,
    author VARCHAR(128) NOT NULL,
    files_changed JSONB NOT NULL DEFAULT '[]'::jsonb,
    diff_summary TEXT,
    merged_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. Log Events Table (Decoupled from incidents to resolve the timeline paradox)
CREATE TABLE log_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    service_name VARCHAR(128) NOT NULL,
    timestamp TIMESTAMPTZ NOT NULL,
    log_level VARCHAR(16) NOT NULL,
    message TEXT NOT NULL,
    stack_trace TEXT,
    metadata JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_log_level CHECK (log_level IN ('DEBUG', 'INFO', 'WARN', 'ERROR', 'FATAL'))
);

-- 6. Hypotheses Table (Generated by AI Orchestrator with evidence citations)
CREATE TABLE hypotheses (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    incident_id UUID NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    description TEXT NOT NULL,
    confidence_score NUMERIC(3,2) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    evidence_citations JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_hypothesis_confidence CHECK (confidence_score >= 0.00 AND confidence_score <= 1.00),
    CONSTRAINT chk_hypothesis_status CHECK (status IN ('PENDING', 'VERIFIED', 'REJECTED'))
);

-- 7. Incident Notes Table (Collaboration layer for on-call engineers)
CREATE TABLE incident_notes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    incident_id UUID NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    hypothesis_id UUID REFERENCES hypotheses(id) ON DELETE SET NULL,
    author VARCHAR(128) NOT NULL,
    note TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ====================================================================
-- Performance Indexes for Time-Window Slicing & Correlation
-- ====================================================================

-- Incidents
CREATE INDEX idx_incidents_status ON incidents(status);
CREATE INDEX idx_incidents_start_time ON incidents(start_time);

-- Alerts
CREATE INDEX idx_alerts_incident_id ON alerts(incident_id);
CREATE INDEX idx_alerts_service_time ON alerts(service_name, triggered_at);

-- Deployments (Crucial for time-window queries: [T - 30m, T + 5m])
CREATE INDEX idx_deployments_service_time ON deployments(service_name, deployment_time);

-- GitHub PRs
CREATE INDEX idx_github_prs_deployment_id ON github_prs(deployment_id);

-- Log Events (High-throughput time-range queries by service and error severity)
CREATE INDEX idx_log_events_service_time ON log_events(service_name, timestamp DESC);
CREATE INDEX idx_log_events_level_time ON log_events(log_level, timestamp DESC);

-- Hypotheses & Collaboration
CREATE INDEX idx_hypotheses_incident_id ON hypotheses(incident_id);
CREATE INDEX idx_incident_notes_incident_id ON incident_notes(incident_id);
